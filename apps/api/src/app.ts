import cookieParser from 'cookie-parser';
import cors from 'cors';
import express from 'express';
import rateLimit from 'express-rate-limit';
import helmet from 'helmet';
import { env } from './config/env';
import { errorHandler } from './middleware/error-handler';
import { notFoundHandler } from './middleware/not-found';
import { healthRouter } from './routes/health.routes';
import { authRouter } from './auth/auth.routes';
import { organizationRouter } from './routes/organization.routes';
import { resourceRouter } from './routes/resource.routes';
import { patientFlowRouter } from './routes/patient-flow.routes';
import { operationsRouter } from './routes/operations.routes';

export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.CLIENT_ORIGIN, methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'], credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: false, limit: '1mb' }));
app.use(cookieParser());
app.use(rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/health', (_req, res) => res.status(200).json({ success: true, data: { service: 'wardpilot-api', status: 'alive' } }));
app.use(`${env.API_BASE_PATH}/health`, healthRouter);
app.use(`${env.API_BASE_PATH}/auth`, authRouter);
app.use(`${env.API_BASE_PATH}/organizations`, organizationRouter);
app.use(`${env.API_BASE_PATH}/resources`, resourceRouter);
app.use(`${env.API_BASE_PATH}/patient-flow`, patientFlowRouter);
app.use(`${env.API_BASE_PATH}/operations`, operationsRouter);
app.use(notFoundHandler);
app.use(errorHandler);
